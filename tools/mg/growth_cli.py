from . import model as m, store, growth as gr, governance as gov, ai, intake
from .cli import ok, warn, err, head, dim, c, C, _confirm


def _save(root: Path, t: gr.Target) -> None:
    store.save_target(root, t)
    store.write_target_artifact(root, t.slug, "TARGET.md", render_target(t))


def _next(t: gr.Target) -> str:
    if t.status == gr.IDENTIFIED:
        return f"mg target research {t.slug}   (then: mg target ingest {t.slug} target-research)"
    if t.status == gr.RESEARCHED:
        return f"mg target assess {t.slug}"
    if t.status == gr.PRIORITIZED:
        act = t.fit.recommended_action
        if act == "Initiate outreach":
            return f"mg target draft {t.slug}"
        if act in ("Monitor", "Wait for trigger"):
            return f"mg target monitor {t.slug} --reason '...'"
        if act == "Disqualify":
            return f"mg target disqualify {t.slug} --reason '...'"
        return f"mg target draft {t.slug}   (or monitor / disqualify)"
    if t.status == gr.CONTACTED:
        last = t.last_touch()
        if last and last.status == "draft":
            return f"mg target approve {t.slug}   (founder review before sending)"
        return f"mg target respond {t.slug} --kind positive|neutral|negative|none"
    if t.status == gr.ENGAGED:
        return f"mg target convert {t.slug}"
    if t.status == gr.MONITORING:
        return f"Monitoring. mg target assess {t.slug} when a trigger appears."
    if t.status == gr.CONVERTED:
        return f"Converted — continue in the sales pipeline: mg status {t.converted_to}"
    return "—"


# --------------------------------------------------------------------------
# Rendering
# --------------------------------------------------------------------------

def render_target(t: gr.Target) -> str:
    def rows(items, fmt, empty="| — | *none* | — |"):
        return "\n".join(fmt(x) for x in items) or empty
    conf = rows(t.confirmed(), lambda e: f"| `{e.ref}` | {e.statement} | {e.source} |")
    inf = rows(t.inferences(), lambda e: f"| `{e.ref}` | {e.statement} | {e.source} |")
    unk = rows(t.unknowns(), lambda e: f"| `{e.ref}` | {e.statement} | — |")
    sig = rows(t.signals,
               lambda s: f"| {s.kind} | {s.signal} | `{s.evidence_ref or '—'}` |",
               "| — | *none matched* | — |")
    touches = rows(
        t.touches,
        lambda x: (f"| {x.seq} | {x.channel or '—'} | {x.purpose[:44] or '—'} | {x.status} | "
                   f"{x.sent_on or '—'} | {x.response_kind or '—'} |"),
        "| — | — | *no outreach* | — | — | — |")
    contacts = rows(t.contacts,
                    lambda x: f"| {x.name or '—'} | {x.role or '—'} | {x.email or '—'} |",
                    "| — | — | — |")
    return f"""<!-- Generated by tools/mg from target.json. Do not edit by hand.
     Procedure: the growth engine. Targets are pre-contact prospects and live
     here, not in clients/, until someone actually engages. -->
# TARGET — {t.company.name or t.slug}

**Status:** {t.status}
**Identified:** {t.identified_on} via {t.identified_via or '*not recorded*'}
**Campaign:** {t.campaign or '—'}
**Industry:** {t.company.industry or '—'} · **Size:** {t.company.approximate_size or '—'}
**Website:** {t.company.website or '—'}

---

## 1. Contacts

*Roles are recorded as published. D-021 sets the expected buyer roles; a role
is still never inferred from a name or a title pattern.*

| Name | Role | Email |
|---|---|---|
{contacts}

## 2. Confirmed Public Information

*Observed, with a source. These are the only statements an outreach message may
rest on.*

| Ref | Statement | Source |
|---|---|---|
{conf}

## 3. Reasoned Inference

*Not observed. **Never stated to a prospect as fact** (`BRAND.md` §6).*

| Ref | Inference | Basis |
|---|---|---|
{inf}

## 4. Unknown

*Recorded rather than filled in.*

| Ref | What is not known | |
|---|---|---|
{unk}

## 5. ICP Signals

*Quoted from `ICP.md`, each tied to the evidence supporting it.*

| Kind | Signal | Evidence |
|---|---|---|
{sig}

## 6. Fit

**Band:** {t.fit.band or '*not assessed*'} · **Recommended action:** {t.fit.recommended_action or '—'}
**Assessed:** {t.fit.assessed_on or '—'}

{t.fit.reasoning or '*No reasoning recorded.*'}

### Unknowns affecting the assessment
{chr(10).join('- ' + u for u in t.fit.unknowns) or '- *None recorded.*'}

## 7. Outreach

| # | Channel | Purpose | Status | Sent | Response |
|---|---|---|---|---|---|
{touches}

{('**Converted to:** `clients/' + t.converted_to + '` on ' + t.converted_on) if t.converted_to else ''}
"""


