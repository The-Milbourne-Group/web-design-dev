def cmd_add(root, a):
    slug = a.slug or m.slugify(a.company)
    if store.target_exists(root, slug) and not a.force:
        err(f"Target {slug} already exists."); return 1
    dupes = store.find_target_duplicates(root, a.company, a.email or "", exclude=slug)
    dupes += [(s, w + " — already in the sales pipeline")
              for s, w in store.find_duplicates(root, a.company, a.email or "")]
    if dupes and not a.duplicate_ok:
        warn(f"{len(dupes)} existing record(s) look like this company:")
        for s2, why in dupes:
            print(f"    {c(s2, C.ACC)} — {why}")
        err("Refusing to create a duplicate. Pass --duplicate-ok if this is genuinely different.")
        return 1
    t = gr.Target(slug=slug, identified_on=m.today(),
                  identified_via=a.via or "", campaign=a.campaign or "")
    t.company.name = a.company
    t.company.website = a.website or ""
    t.company.industry = a.industry or ""
    t.company.approximate_size = a.size or ""
    t.company.location = a.location or ""
    if a.contact or a.email:
        t.contacts.append(m.Contact(name=a.contact or "", role=a.role or "",
                                    email=a.email or ""))
    t.log("identified", f"via {a.via or 'unrecorded'}", a.actor)
    _save(root, t)
    ok(f"Target {c(slug, C.ACC)} — {a.company}")
    if not a.via:
        warn("  No --via recorded. How targets are found is what tests the D-026 channel order.")
    print(f"\n{c('Next:', C.B)} {_next(t)}")
    return 0


